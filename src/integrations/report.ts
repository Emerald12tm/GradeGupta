import { formatAverage, letterGrade } from '@/grades/average';
import type { GpaResult } from '@/grades/gpa';
import type { Course } from '@/hac/types';

/**
 * Text builders for sharing: the grade report PDF (as HTML for expo-print) and
 * pre-filled teacher emails. Pure, so they're unit tested.
 */

/** Escapes text for HTML. Course and assignment names come from HAC and must not inject markup. */
export const escapeHtml = (s: string): string =>
  s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;').replace(/'/g, '&#39;');

export function gradeReportHtml(input: { student?: string; courses: Course[]; gpa: GpaResult; generatedAt: Date }): string {
  const rows = input.courses
    .map((c) => {
      const missing = c.assignments.filter((a) => a.isMissing).length;
      return `<tr><td>${escapeHtml(c.name)}</td><td class="n">${formatAverage(c.reportedAverage)}</td><td class="n">${letterGrade(c.reportedAverage)}</td><td class="n">${missing || ''}</td></tr>`;
    })
    .join('');
  return `<!doctype html><html><head><meta charset="utf-8"><style>
body{font-family:-apple-system,Roboto,Helvetica,Arial,sans-serif;color:#11181C;padding:32px}
h1{font-size:24px;margin:0 0 4px}p{color:#5A5F67;margin:0 0 20px}
table{width:100%;border-collapse:collapse;font-size:14px}th,td{padding:8px;border-bottom:1px solid #E2E4EA;text-align:left}
th{color:#5A5F67;font-size:12px;text-transform:uppercase}.n{text-align:right}
.gpa{display:flex;gap:32px;margin:0 0 20px}.gpa b{font-size:22px;display:block}
footer{margin-top:24px;color:#5A5F67;font-size:11px}
</style></head><body>
<h1>Grade report${input.student ? ` · ${escapeHtml(input.student)}` : ''}</h1>
<p>Generated ${escapeHtml(input.generatedAt.toLocaleString())}</p>
<div class="gpa"><div><b>${input.gpa.weighted?.toFixed(3) ?? '—'}</b>Weighted GPA</div><div><b>${input.gpa.unweighted?.toFixed(3) ?? '—'}</b>Unweighted GPA</div></div>
<table><thead><tr><th>Class</th><th class="n">Average</th><th class="n">Letter</th><th class="n">Missing</th></tr></thead><tbody>${rows}</tbody></table>
<footer>Unofficial report generated by GradeGupta from Home Access Center. Your school’s records are the official ones.</footer>
</body></html>`;
}

/** A mailto: link to a teacher about a class (and optionally a specific assignment). */
export function teacherMailto(email: string, courseName: string, assignmentName?: string): string {
  const subject = assignmentName ? `${courseName}: ${assignmentName}` : courseName;
  const body = assignmentName
    ? `Hi,\n\nI have a question about "${assignmentName}" in ${courseName}.\n\nThank you,`
    : `Hi,\n\nI have a question about ${courseName}.\n\nThank you,`;
  return `mailto:${email}?subject=${encodeURIComponent(subject)}&body=${encodeURIComponent(body)}`;
}
